const WORD_BOUNDARY = /[\p{L}\p{N}]/u;

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** Lowercase + strip diacritics so "café" matches "cafe". */
function fold(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

interface CompiledEntry {
  keyword: string;
  emoji: string;
  regex: RegExp;
}

// Longest keywords first: "train station" wins over "train".
const COMPILED: CompiledEntry[] = [...ENTRIES]
  .sort((a, b) => b[0].length - a[0].length)
  .map(([keyword, emoji]) => ({
    keyword,
    emoji,
    regex: new RegExp(`(^|[^\\p{L}\\p{N}])${escapeRegExp(keyword)}([^\\p{L}\\p{N}]|$)`, 'iu'),
  }));

/**
 * Best-effort emoji for a word's translation. Returns null when nothing in
 * the map plausibly matches (callers then show no hint rather than a
 * misleading one).
 */
export function emojiForText(text: string | null | undefined): string | null {
  if (!text) return null;
  const folded = fold(text);
  if (!WORD_BOUNDARY.test(folded)) return null; // nothing but symbols/whitespace
  for (const entry of COMPILED) {
    if (entry.regex.test(folded)) return entry.emoji;
  }
  return null;
}
